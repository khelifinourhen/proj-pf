"""## 14. Feature Engineering"""

def add_engineered_features(data):
    d = data.copy()

    d["temp_delta_ambient"] = d["temperature_c"] - d["ambient_temp_c"]
    d["thermal_load_index"] = d["temperature_c"] * d["load_pct"] / 100.0

    d["vibration_energy"] = d["vibration_norm_ms2"] ** 2
    d["vibration_per_krpm"] = (
        1000 * d["vibration_norm_ms2"] / (d["rpm"].abs() + 1.0)
    )

    d["voltage_deviation_v"] = (d["voltage_v"] - 28.0).abs()
    d["calculated_power_w"] = d["voltage_v"] * d["current_a"]
    d["power_sensor_error_w"] = (
        d["power_w"] - d["calculated_power_w"]
    ).abs()
    d["power_per_load"] = d["power_w"] / (d["load_pct"].abs() + 1.0)

    d["pressure_ratio_atm"] = (
        d["pressure_hpa"] /
        (d["atmospheric_pressure_hpa"].abs() + 1.0)
    )

    d["maintenance_stress_index"] = (
        d["load_pct"] * (1 + d["maintenance_age_days"]/180.0)
    )
    d["age_load_interaction"] = (
        np.log1p(d["operating_hours"].clip(lower=0))
        * d["load_pct"]
    )

    ts = pd.to_datetime(d["timestamp"])
    hour = ts.dt.hour + ts.dt.minute/60
    d["hour_sin"] = np.sin(2*np.pi*hour/24)
    d["hour_cos"] = np.cos(2*np.pi*hour/24)

    return d

