def iqr_analysis(series):
    s = series.dropna()
    q1, q3 = s.quantile([0.25, 0.75])
    iqr = q3 - q1
    low = q1 - 1.5*iqr
    high = q3 + 1.5*iqr
    count = int(((s < low) | (s > high)).sum())
    return count, low, high

def zscore_count(series, threshold=3.0):
    s = series.dropna()
    z = (s - s.mean()) / (s.std() + 1e-12)
    return int((z.abs() > threshold).sum())

